-- Commentaires publics via fonctions atomiques ; administration via RLS.

create table if not exists public.comment_submissions (
  id bigint generated by default as identity primary key,
  ip_hash text not null,
  created_at timestamptz not null default now()
);

create index if not exists idx_comment_submissions_ip_created_at
on public.comment_submissions(ip_hash, created_at desc);

alter table public.comment_submissions enable row level security;
revoke all on table public.comment_submissions from anon, authenticated;
revoke all on sequence public.comment_submissions_id_seq from anon, authenticated;
grant select, insert, delete on table public.comment_submissions to service_role;
grant usage, select on sequence public.comment_submissions_id_seq to service_role;

create table if not exists public.comment_likes (
  comment_id bigint not null references public.comments(id) on delete cascade,
  client_hash text not null,
  created_at timestamptz not null default now(),
  primary key (comment_id, client_hash)
);

alter table public.comment_likes enable row level security;
revoke all on table public.comment_likes from anon, authenticated;
grant select, insert, delete on table public.comment_likes to service_role;

